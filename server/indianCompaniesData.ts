function capitalize(s: string): string {
  if (!s) return 'Bharat';
  return s.charAt(0).toUpperCase() + s.slice(1);
}

function cleanName(s: string): string {
  if (!s) return 'tech';
  return s.toLowerCase().replace(/[^a-z0-9]/g, '');
}
